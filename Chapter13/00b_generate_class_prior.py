"""
chapter13/code/00b_generate_class_prior.py

Generate a class-prior dataset for DreamBooth training.

Prior preservation needs ~200 images of the broader class your subject
belongs to ("dog" if you're training one specific dog, "lamp" if you're
training one specific lamp, etc.), generated by the BASE Stable Diffusion
model. Training on these alongside your subject images stops the model
from collapsing the whole concept of "dog" onto your specific dog.

This script does just that one thing. It's split out from the training
loop so you can:
- generate the class set once and reuse it across many training runs
- inspect the generated images and drop bad ones before training
- resume an interrupted generation (existing files are skipped)
- swap models or settings independently of training

Run:
    python 00b_generate_class_prior.py \
        --class_prompt "a photo of a dog" \
        --out_dir ./class_dog \
        --count 200

Tips:
- 200 images is the canonical number. You can get away with 100, but
  not with 50.
- 20 inference steps is enough for class-prior images. They don't need
  to be masterpieces; they just need to look like "a dog."
- This takes 10-15 minutes on a consumer GPU for 200 images at 512px.
  You only do it once per class.
"""

import argparse
from pathlib import Path

import torch
from diffusers import StableDiffusionPipeline, DPMSolverMultistepScheduler

MODEL_ID = "runwayml/stable-diffusion-v1-5"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--class_prompt", required=True,
                    help='caption for class-prior images, e.g. "a photo of a dog"')
    ap.add_argument("--out_dir", required=True,
                    help="where to write the generated class images")
    ap.add_argument("--count", type=int, default=200,
                    help="how many class-prior images to generate")
    ap.add_argument("--steps", type=int, default=20,
                    help="inference steps per image (20 is plenty)")
    ap.add_argument("--guidance", type=float, default=7.0,
                    help="classifier-free guidance scale")
    ap.add_argument("--negative_prompt", default="",
                    help="optional negative prompt (e.g. 'blurry, watermark')")
    ap.add_argument("--seed", type=int, default=0,
                    help="base seed; each image uses seed + index for variety")
    ap.add_argument("--model_id", default=MODEL_ID,
                    help="base SD model to generate FROM (must match the one"
                         " you'll fine-tune)")
    args = ap.parse_args()

    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    # Find what's already on disk so we can resume.
    existing = sorted(p for p in out.glob("class_*.png"))
    start_idx = len(existing)
    if start_idx >= args.count:
        print(f"already have {start_idx} images in {out}; nothing to do")
        return
    if start_idx > 0:
        print(f"resuming: found {start_idx} existing images, "
              f"generating {args.count - start_idx} more")

    device = "cuda" if torch.cuda.is_available() else "cpu"
    if device != "cuda":
        print("WARNING: running on CPU. This will be very slow.")

    pipe = StableDiffusionPipeline.from_pretrained(
        args.model_id,
        torch_dtype=torch.float16 if device == "cuda" else torch.float32,
        safety_checker=None,
    )
    pipe.scheduler = DPMSolverMultistepScheduler.from_config(pipe.scheduler.config)
    pipe = pipe.to(device)
    pipe.set_progress_bar_config(disable=True)

    print(f"generating {args.count - start_idx} images "
          f"with prompt: {args.class_prompt!r}")

    for i in range(start_idx, args.count):
        # Each image gets a different seed so we get variety, not 200 copies.
        gen = torch.Generator(device=device).manual_seed(args.seed + i)
        image = pipe(
            prompt=args.class_prompt,
            negative_prompt=args.negative_prompt or None,
            num_inference_steps=args.steps,
            guidance_scale=args.guidance,
            generator=gen,
        ).images[0]
        image.save(out / f"class_{i:04d}.png")
        if (i + 1) % 10 == 0 or i == args.count - 1:
            print(f"  {i + 1}/{args.count} generated")

    print(f"\ndone. {args.count} class-prior images in {out.resolve()}")
    print("\nnext step:")
    print(f"  python 03_train_dreambooth_lora.py \\")
    print(f"      --subject_dir ./dog_subject \\")
    print(f"      --class_dir   {out} \\")
    print(f"      --instance_prompt 'a photo of sks dog' \\")
    print(f"      --class_prompt   {args.class_prompt!r} \\")
    print(f"      --out_dir     ./dog_lora")


if __name__ == "__main__":
    main()
